"""Writes each DRLA gun's base tics between shots, for the Automatics fire-rate bands (skillperks 09).

usage: python tools/automatics/derive_bands.py [--drla DIR] [--write | --check]

The owner's rule (2026-11-27): a gun's band is inherent to it, from its base time between shots in its primary fire:
4 or more tics slow, 3 middle, 1-2 fast. "Base" means without mods, perks or other fire-rate bonuses; a gun that spins
up (the minigun) counts at full speed. derive_rifles.trace_fire already walks a DRLA gun's Fire state with the trigger
held, no mods and ammo loaded, until it settles into its loop, and gives the closest two shots in that loop: that is the
spun-up rate. A gun that never fires while fire is held is measured pressed once per shot, as derive_rifles does.

Every DRLA gun that could be an Automatic (gives the rapid-fire token, or is on DoomerfallWeaponCategory's owner list
of Automatics, or the Grammaton Cleric Beretta) is listed; Doom reads the table only for guns whose skill is
Automatics. A gun the walk cannot measure is left out and gets no band (see the notes). --write puts the table into
mods/doomerfall/src/zscript/DoomerfallAutomaticBands.zs between the GENERATED markers; --check fails if it is stale.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'rifle_tag'))
import derive_rifles as d  # noqa: E402

TABLE_FILE = os.path.join(d.REPO, 'mods', 'doomerfall', 'src', 'zscript', 'DoomerfallAutomaticBands.zs')
EXTRA = {'rlgrammatonclericberetta'}  # Pistol + Automatic by the owner's dual-tag rule


def owner_automatics():
    with open(d.CATEGORY_FILE, encoding='utf-8') as f:
        text = f.read()
    m = re.search(r'automatics\[\]\s*=\s*\{(.*?)\};', text, re.S)
    return {n.lower() for n in re.findall(r'"(\w+)"', d.strip_comments(m.group(1)))} | EXTRA


def derive(drla):
    actors = d.load_actors(drla)
    own = owner_automatics()
    rows, missing = [], []
    for key, a in sorted(actors.items()):
        anc = d.ancestors(actors, a.name)
        if ('weapon' not in anc and 'rlweapon' not in anc) or 'fire' not in a.labels:
            continue
        if 'rapidfire' not in d.tokens(a) and key not in own:
            continue
        ammo = {x.lower() for x in (d.prop(actors, a, k) for k in ('weapon.ammotype', 'weapon.ammotype1', 'weapon.ammotype2')) if x}
        gap, shots, _, note = d.trace_fire(actors, a, ammo)
        if not shots:
            gap, shots, _, note = d.trace_fire(actors, a, ammo, held=False)
        if shots and gap and gap > 0:
            rows.append((a.name, int(round(gap))))
        else:
            missing.append((a.name, note))
    return rows, missing


def render(rows):
    names = ''.join('\t\t\t"%s",\n' % n for n, _ in rows)
    tics = ''.join('\t\t\t%d,\n' % t for _, t in rows)
    return ('\t\t// GENERATED by tools/automatics/derive_bands.py --write. Do not edit by hand.\n'
            '\t\tstatic const String names[] = {\n' + names + '\t\t\t""\n\t\t};\n'
            '\t\tstatic const int tics[] = {\n' + tics + '\t\t\t0\n\t\t};\n'
            '\t\t// END GENERATED\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--drla', default=d.DEFAULT_DRLA)
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    args = ap.parse_args()
    rows, missing = derive(args.drla)
    for n, note in missing:
        print('no band:', n, '-', note)
    block = render(rows)
    with open(TABLE_FILE, encoding='utf-8') as f:
        text = f.read()
    m = re.search(r'\t*// GENERATED by .*?// END GENERATED\n', text, re.S)
    if not m:
        sys.exit('no GENERATED block in ' + TABLE_FILE)
    if args.write:
        with open(TABLE_FILE, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text[:m.start()] + block + text[m.end():])
        print('wrote %d guns' % len(rows))
    elif args.check:
        if m.group(0) != block:
            sys.exit('DoomerfallAutomaticBands.zs is stale: run derive_bands.py --write')
        print('ok: %d guns' % len(rows))
    else:
        for n, t in rows:
            print(n, t)


if __name__ == '__main__':
    main()
