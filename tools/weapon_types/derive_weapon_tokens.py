"""Writes the DRLA weapon type tokens each gun gives, so Doomerfall can name a gun's weapon types while it is not held
(todo: weapontypes 01, the Daggerfall item description).

usage: python tools/weapon_types/derive_weapon_tokens.py [--drla DIR] [--write | --check]

DoomerfallWeaponCategory.Both reads DRLA's RL*TypeWeapon tokens from the player's inventory, and DRLA gives them only
while a gun is held (its Select state calls A_GiveInventory). A gun lying in Daggerfall's inventory has no tokens to
read. This script reads which tokens each DRLA gun's DECORATE gives and writes them into
mods/doomerfall/src/zscript/DoomerfallWeaponTokens.zs between the GENERATED markers, as the bits
DoomerfallWeaponCategory.Tok* define. BothOfClass uses that table with the same rules as Both.
--check fails if the committed table differs from what DRLA's files give now.
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.join(os.path.dirname(HERE), 'rifle_tag'))
import derive_rifles  # noqa: E402  (shares its DECORATE loader)

REPO = derive_rifles.REPO
TABLE_FILE = os.path.join(REPO, 'mods', 'doomerfall', 'src', 'zscript', 'DoomerfallWeaponTokens.zs')
# Must match DoomerfallWeaponCategory's Tok* constants.
BITS = {'pistol': 1, 'shotgun': 2, 'singleshotrifle': 4, 'rapidfire': 8, 'melee': 16}
TOKEN = re.compile(r'A_GiveInventory\s*\(\s*"RL(\w+?)TypeWeapon"', re.I)


def derive(drla):
    actors = derive_rifles.load_actors(drla)
    rows = []
    for a in actors.values():
        bits = 0
        for t in TOKEN.findall(a.body):
            bits |= BITS.get(t.lower(), 0)
        if bits:
            rows.append((a.name, bits))
    return sorted(rows, key=lambda r: r[0].lower())


def render(rows):
    # Inside DoomerfallWeaponTokens.Of: ZScript static functions cannot see class-scope static arrays.
    names = ''.join('\t\t\t"%s",\n' % n for n, _ in rows)
    bits = ''.join('\t\t\t%d,\n' % b for _, b in rows)
    return ('\t\t// GENERATED by tools/weapon_types/derive_weapon_tokens.py --write. Do not edit by hand.\n'
            '\t\tstatic const String names[] = {\n' + names + '\t\t\t""\n\t\t};\n'
            '\t\tstatic const int bits[] = {\n' + bits + '\t\t\t0\n\t\t};\n'
            '\t\t// END GENERATED\n')


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--drla', default=derive_rifles.DEFAULT_DRLA)
    g = ap.add_mutually_exclusive_group()
    g.add_argument('--write', action='store_true')
    g.add_argument('--check', action='store_true')
    args = ap.parse_args()
    rows = derive(args.drla)
    block = render(rows)
    with open(TABLE_FILE, encoding='utf-8') as f:
        text = f.read()
    m = re.search(r'\t*// GENERATED by .*?// END GENERATED\n', text, re.S)
    if not m:
        sys.exit('no GENERATED block in ' + TABLE_FILE)
    if args.write:
        with open(TABLE_FILE, 'w', encoding='utf-8', newline='\n') as f:
            f.write(text[:m.start()] + block + text[m.end():])
        print('wrote %d guns' % len(rows))
    elif args.check:
        if m.group(0) != block:
            sys.exit('DoomerfallWeaponTokens.zs is stale: run derive_weapon_tokens.py --write')
        print('ok: %d guns' % len(rows))
    else:
        for n, b in rows:
            print(n, b)


if __name__ == '__main__':
    main()
