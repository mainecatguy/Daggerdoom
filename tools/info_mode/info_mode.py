def run(name, stock_mods, night=False):
    data, runs = REVIEW / "data", REVIEW / "run"
    saves = runs / "saves"
    saves.mkdir(parents=True, exist_ok=True)
    uz_log, df_log, console, launcher = runs / f"{name}-uz.log", runs / f"{name}-df.log", runs / f"log-{name}.txt", runs / f"{name}-launcher.log"
    for path in (uz_log, df_log, console, launcher):
        path.unlink(missing_ok=True)
    door = building_door("GeneralStore")
    text = (HERE / "harness.zs").read_text().replace("@DOOR@", ", ".join(door[3:8]))
    harness = runs / f"{name}_harness.pk3"
    with zipfile.ZipFile(harness, "w") as z:
        z.writestr("zscript.txt", text)
        z.writestr("mapinfo.txt", 'gameinfo { addeventhandlers = "IMHarness" }\n')
    uz = ["-noactivate", "-config", str(runs / f"{name}.ini"), "-savedir", str(saves), "-dfbridgelog", str(uz_log), "-nosound", "-noautoload", "-skill", "3",
          "-ddtowncache", str(data / "cache"), "-ddconverter", str(data / "converter" / "DungeonConverter.exe"), "-ddarena2", str(GAME / "DAGGER" / "ARENA2"),
          "+logfile", name, "+screenshot_dir", str(runs / f"{name}-shots"),"+vid_fullscreen", "0", "+wipetype", "0", "+i_pauseinbackground", "0", "+vid_activeinbackground", "1", "+vid_lowerinbackground", "0", "+map", f"DDT{GROUP:05d}"]
    df = ["-dfbridgelog", str(df_log), "-dfsynctest", str(GAME / "DAGGER"), "-dfloottest", "-screen-fullscreen", "0", "-screen-width", "640", "-screen-height", "360"] + (["-dfnpcreport", "-dfnpcnight"] if night else [])
    timeout = 90
    command = [sys.executable, QUIET, "--timeout", str(timeout), "--", str(REVIEW / "doomerfall-launcher.exe"), "--minimized", "--nodraw",
               "--uzdoom", str(REVIEW / "uzdoom" / "uzdoom.exe"), "--dfu", str(REVIEW / "dfu" / "DaggerfallUnity.exe"), "--iwad", str(GAME / "wads" / "DOOM2.WAD"),
               "--uzdoom-cwd", str(runs), "--log", str(launcher)]
    mods = ([] if stock_mods else [MODS / n for n in DRLA]) + [data / n for n in DUNGEON] + [REVIEW / "dfitems.pk3", REVIEW / "doomerfall.pk3", harness]
    for mod in mods:
        command += ["--mod", str(mod)]
    for arg in uz:
        command += ["--uzdoom-arg", arg]
    for arg in df:
        command += ["--dfu-arg", arg]
    proc = subprocess.Popen(command, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    reason, end = "timeout", time.time() + timeout + 3
    while time.time() < end and proc.poll() is None:
        time.sleep(0.25)
        body = read(console)
        if "IMDONE" in body:
            reason = "route finished"
            time.sleep(1)
            break
        if any(k in body for k in FATAL):
            reason = "fatal"
            break
    if proc.poll() is None:
        subprocess.call(["taskkill", "/F", "/T", "/PID", str(proc.pid)], stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        proc.wait()
    print("stopped:", reason)
    # Each press, then what Doom printed until the next harness line: the messages the player sees.
    shown = False
    for line in read(console).splitlines():
        if re.match(r"IM[A-Z]+ ", line):
            print(line[:190])
            shown = line.startswith("IMPRESS")
        elif any(k in line for k in FATAL):
            print(line[:190])
        elif shown and line.strip() and not line.startswith(("DD", "DFGATES", "Doomerfall:", "[bridge]")):
            print("   doom shows:", line[:170])
    for line in read(df_log).splitlines():
        if re.search(r"info:|items: (use|opening|closed)|loottest:|ui: menu|error", line):
            print("df", line[:230])
    kinds = sorted({l[:150] for l in read(REVIEW / "dfu" / "PortableAppdata" / "Player.log").splitlines() if "Exception" in l})
    print("Player.log exception kinds:", len(kinds))
    for line in kinds[:5]:
        print("  ", line)


def check():
    runs = REVIEW / "run"
    runs.mkdir(parents=True, exist_ok=True)
    drla = [str(MODS / n) for n in DRLA]
    for label, mods in (("stock", []), ("drla", drla), ("drla-doomerfall", drla + [str(REVIEW / "doomerfall.pk3")])):
        log = runs / f"log-check-{label}.txt"  # UZDoom names the log file log-NAME.txt
        log.unlink(missing_ok=True)
        command = [sys.executable, QUIET, "--timeout", "30", "--cwd", str(runs), "--", str(REVIEW / "uzdoom" / "uzdoom.exe"), "-noactivate", "-iwad", str(GAME / "wads" / "DOOM.WAD"),
                   "-config", str(runs / f"check-{label}.ini"), "-nosound", "-noautoload", "-skill", "3", "-file", *mods, "+logfile", f"check-{label}",
                   "+i_pauseinbackground", "0", "+vid_activeinbackground", "1", "+vid_lowerinbackground", "0", "+vid_fullscreen", "0", "+map", "E1M1", "+wait 140;quit"]
        code = subprocess.call(command, stdin=subprocess.DEVNULL, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        body = read(log)
        print(label, "exit", code, "| bridge lines", sum("bridge" in l.lower() for l in body.splitlines()), "| script errors", sum("Script error" in l for l in body.splitlines()),
              "| unknown class", sum("Unknown" in l for l in body.splitlines()), "| fatal", any(k in body for k in FATAL))


