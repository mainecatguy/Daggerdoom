"""Writes mods/doomerfall/src/TEXTURES.ammoicons: one tinted status bar icon per ammo type and tier (card ammoicon).

Each icon is the type's Doom pickup sprite (CLIPA0, SHELA0, ROCKA0, CELLA0) with that tier's colour, the same
translation the tiered pickups use (DFAmmoTier<n> in mods/doomerfall/src/TRNSLATE, read here so the two never drift).
DoomerfallAmmoTiers (DoomerfallAmmo.zs) gives the player's reserve ammo item the loaded tier's icon, so every HUD that
draws the ammo's icon (DRLA's SBARINFO, Doom's status bar, the alternative HUD) shows the tier.

Sizes and offsets are the sprites' own, the same in DOOM.WAD, DOOM2.WAD and DRLA (graphics/patches).
Names: DFAI<type letter><tier>, such as DFAIC2 for Silver bullets. Run again after changing TRNSLATE's tier colours.
"""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SRC = REPO / "mods" / "doomerfall" / "src"
# (letter, sprite, width, height, left offset, top offset), in DoomerfallAmmoTiers' type order.
TYPES = [("C", "CLIPA0", 9, 11, 2, 11), ("S", "SHELA0", 15, 7, 5, 7), ("R", "ROCKA0", 12, 27, 6, 27), ("E", "CELLA0", 17, 12, 8, 12)]

tiers = dict(re.findall(r'^DFAmmoTier(\d+)\s*=\s*"([^"]+)"', (SRC / "TRNSLATE").read_text(), re.M))
out = ["// Generated by tools/ammoicon/make_textures.py from TRNSLATE's DFAmmoTier colours. Do not edit by hand.", ""]
for letter, sprite, w, h, x, y in TYPES:
    for tier in sorted(tiers, key=int):
        out += [f'Graphic "DFAI{letter}{tier}", {w}, {h}', "{", f"\tOffset {x}, {y}",
                f'\tPatch "{sprite}", 0, 0 {{ Translation "{tiers[tier]}" }}', "}"]
(SRC / "TEXTURES.ammoicons").write_text("\n".join(out) + "\n", newline="\n")
print("wrote", SRC / "TEXTURES.ammoicons", len(tiers) * len(TYPES), "icons")
